// ── Iconos con relleno sólido ──
const FILL_ICONS = new Set(['play']);

// ── Renderizado de icono por nombre ──
export function icon(name, className = 'ui-icon') {
    const body = ICONS[name];
    if (!body) return '';
    const fill = FILL_ICONS.has(name) ? 'currentColor' : 'none';
    const stroke = FILL_ICONS.has(name) ? 'none' : 'currentColor';
    return `<svg class="${className}" viewBox="0 0 24 24" fill="${fill}" stroke="${stroke}" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${body}</svg>`;
}

// ── Mapeo de habilidades R/L/S/W ──
export const SKILL_ICONS = {
    R: 'book',
    L: 'headphones',
    S: 'mic',
    W: 'pen'
};

// ── Icono por letra de habilidad ──
export function skillIcon(letter, className = 'ui-icon ui-icon--xs') {
    const key = SKILL_ICONS[letter];
    return key ? icon(key, className) : '';
}

